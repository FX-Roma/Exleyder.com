/* eslint-disable no-console */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const dotenv = require('dotenv');

const projectRoot = path.resolve(__dirname, '..');
const envPath = path.join(projectRoot, '.env');
const outputPath = path.join(
  projectRoot,
  'src',
  'app',
  'pages',
  'contact',
  'static-forms.config.ts',
);

// Local development reads .env; Vercel injects configured variables into process.env.
if (fs.existsSync(envPath)) {
  dotenv.config({ path: envPath, quiet: true });
}

const apiKey = process.env.STATIC_FORMS_API_KEY?.trim();

if (!apiKey || !apiKey.startsWith('sf_')) {
  console.error(
    '[STATIC_FORMS_CONFIG_ERROR] Set STATIC_FORMS_API_KEY to the form key beginning with "sf_" in .env or Vercel Environment Variables.',
  );
  process.exit(1);
}

const generatedSource = `// Generated by scripts/generate-static-forms-config.cjs. Do not edit or commit.\n` +
  `// Static Forms submission keys are public identifiers and are embedded in the client bundle.\n` +
  `export const STATIC_FORMS_API_KEY = ${JSON.stringify(apiKey)};\n`;

fs.writeFileSync(outputPath, generatedSource, { encoding: 'utf8', mode: 0o600 });
console.log('[STATIC_FORMS_CONFIG] Public form configuration generated.');
